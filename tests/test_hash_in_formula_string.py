"""A `#` inside a string literal in a header formula is data (§4.2 rules 6, 8).

`string = DQUOTE *( char - DQUOTE ) DQUOTE`, and `char` includes `#`, so
`if(a = "#4", 1, 2)` is generated by `formula` and is accepted. Rule 8 refuses
a `#` outside the grammar, such as `a * 2 #note`; that one is still
`malformed-formula` (§9.20).

Unit tests of the two implementations, not conformance cases: the cases for
this rule come from an author who has not read `reference/`.
"""

import importlib

import pytest

IMPLS = pytest.mark.parametrize("impl", ["rowspec.table", "rowspec_alt.table"])

SRC = "| id | a | t = {} |\n| -- | -- | -: |\n| r_1 | {v} |  |\n| r_2 | 5 |  |\n"

INSIDE = {
    "leading": ('if(a = "#4", 1, 2)', "#4", ["1.0", "2.0"]),
    "trailing": ('if(a = "4#", 1, 2)', "4#", ["1.0", "2.0"]),
    "only": ('if(a = "#", 1, 2)', "#", ["1.0", "2.0"]),
    "after-space": ('if(a = "x #y", 1, 2)', "x #y", ["1.0", "2.0"]),
    "error-spelling": ('if(a = "#REF!(zz)", 1, 2)', "#REF!(zz)", ["1.0", "2.0"]),
    "not-equal": ('if(a <> "#ff8800", 1, 2)', "#ff8800", ["2.0", "1.0"]),
    "in-a-branch": ('if(a = "#4", if(a = "#5", 3, 1), 2)', "#4", ["1.0", "2.0"]),
}


@IMPLS
@pytest.mark.parametrize("formula,value,want", list(INSIDE.values()), ids=list(INSIDE))
def test_a_hash_inside_a_string_literal_is_accepted(impl, formula, value, want):
    rows, _ = importlib.import_module(impl).evaluate(SRC.format(formula, v=value))
    assert [str(r["t"]) for r in rows] == want


OUTSIDE = {
    "trailing-note": 'if(a = "x", 1, 2) #note',
    "after-a-string": 'if(a = "x"#, 1, 2)',
    "arithmetic": "a * 2 #note",
    "unclosed-string": 'if(a = "#4, 1, 2)',
    "between-strings": 'if(a = "x", 1, 2) # "y"',
}


@IMPLS
@pytest.mark.parametrize("formula", list(OUTSIDE.values()), ids=list(OUTSIDE))
def test_a_hash_outside_a_string_literal_is_still_refused(impl, formula):
    table = importlib.import_module(impl)
    with pytest.raises(table.Malformed) as e:
        table.evaluate(SRC.format(formula, v="x"))
    assert e.value.refusal == "malformed-formula"
